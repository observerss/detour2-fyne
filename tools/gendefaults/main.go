// gendefaults writes the built-in upstream lines into a gitignored Go file,
// so addresses and passwords live in build.env (also gitignored) instead of
// the source tree.
//
// Values come from the environment first, then from the config file:
//
//	DETOUR2_DEFAULT_PROFILES=hk=tcp://host:17780;jp=tcp://host:7777
//	DETOUR2_DEFAULT_PROFILE=hk
//	DETOUR2_DEFAULT_PASSWORD=secret
//
// Lines are separated by ";" because a single line may already list several
// upstreams separated by ",".
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
)

const (
	keyProfiles = "DETOUR2_DEFAULT_PROFILES"
	keyDefault  = "DETOUR2_DEFAULT_PROFILE"
	keyPassword = "DETOUR2_DEFAULT_PASSWORD"
)

type line struct {
	name, remote string
}

func main() {
	config := flag.String("config", "build.env", "KEY=VALUE file with the built-in lines")
	out := flag.String("o", "defaults_gen.go", "output Go file")
	pkg := flag.String("pkg", "profile", "package name of the output file")
	flag.Parse()

	if err := run(*config, *out, *pkg); err != nil {
		fmt.Fprintln(os.Stderr, "gendefaults:", err)
		os.Exit(1)
	}
}

func run(config, out, pkg string) error {
	values, err := readConfig(config)
	if err != nil {
		return err
	}
	for _, key := range []string{keyProfiles, keyDefault, keyPassword} {
		if v, ok := os.LookupEnv(key); ok {
			values[key] = v
		}
	}
	lines, err := parseLines(values[keyProfiles])
	if err != nil {
		return err
	}
	password := values[keyPassword]
	defaultName := strings.TrimSpace(values[keyDefault])
	if len(lines) == 0 {
		fmt.Fprintf(os.Stderr, "gendefaults: warning: %s not set (see build.env.example); the app will ship without built-in lines\n", keyProfiles)
		defaultName = ""
	} else {
		if password == "" {
			return fmt.Errorf("%s is required when %s is set", keyPassword, keyProfiles)
		}
		if defaultName == "" {
			defaultName = lines[0].name
		}
		if !hasLine(lines, defaultName) {
			return fmt.Errorf("%s=%q is not one of %s", keyDefault, defaultName, keyProfiles)
		}
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tools/gendefaults from build.env; DO NOT EDIT. DO NOT COMMIT.\n\npackage %s\n\n", pkg)
	fmt.Fprintf(&b, "func init() {\n\tDefaultProfileName = %s\n\tbuiltinProfiles = []Profile{\n", strconv.Quote(defaultName))
	for _, l := range lines {
		fmt.Fprintf(&b, "\t\t{Name: %s, RemoteAddress: %s, Password: %s},\n", strconv.Quote(l.name), strconv.Quote(l.remote), strconv.Quote(password))
	}
	b.WriteString("\t}\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile(out, src, 0o600)
}

func parseLines(value string) ([]line, error) {
	var lines []line
	for _, item := range strings.Split(value, ";") {
		item = strings.TrimSpace(item)
		if item == "" {
			continue
		}
		name, remote, ok := strings.Cut(item, "=")
		name, remote = strings.TrimSpace(name), strings.TrimSpace(remote)
		if !ok || name == "" || remote == "" {
			return nil, fmt.Errorf("%s: expected name=address, got %q", keyProfiles, item)
		}
		if hasLine(lines, name) {
			return nil, fmt.Errorf("%s: duplicate line %q", keyProfiles, name)
		}
		lines = append(lines, line{name: name, remote: remote})
	}
	return lines, nil
}

func hasLine(lines []line, name string) bool {
	for _, l := range lines {
		if l.name == name {
			return true
		}
	}
	return false
}

// readConfig parses KEY=VALUE lines; a missing file yields no values.
func readConfig(path string) (map[string]string, error) {
	values := map[string]string{}
	f, err := os.Open(path)
	if err != nil {
		if os.IsNotExist(err) {
			return values, nil
		}
		return nil, err
	}
	defer f.Close()
	scanner := bufio.NewScanner(f)
	for n := 1; scanner.Scan(); n++ {
		text := strings.TrimSpace(scanner.Text())
		if text == "" || strings.HasPrefix(text, "#") {
			continue
		}
		key, value, ok := strings.Cut(text, "=")
		if !ok {
			return nil, fmt.Errorf("%s:%d: expected KEY=VALUE", path, n)
		}
		value = strings.TrimSpace(value)
		if unquoted, err := strconv.Unquote(value); err == nil {
			value = unquoted
		}
		values[strings.TrimSpace(key)] = value
	}
	return values, scanner.Err()
}
